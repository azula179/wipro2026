package ncrb;

public class offender {
	int id;
	String name;
	int age;
	int height;
	String gang_affil;
	String status;
	int reg_cases;
	int sentence;
	
	public offender(int id,
	String name,
	int age,
	int height,
	String gang_affil,
	String status,
	int reg_cases,
	int sentence){
		
	this.id=id;
	this.name=name;
	this.age=age;
	this.height=height;
	this.gang_affil=gang_affil;
	this.status=status;
	this.reg_cases=reg_cases;
	this.sentence=sentence;
	
	}	
}
